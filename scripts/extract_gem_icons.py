# Build the gem name → picture table the Gems section uses for gems the Character
# hasn't socketed (socketed gems bring their own picture from the items import).
# Usage: python3 scripts/extract_gem_icons.py <RePoE base_items.json> <RePoE gems.json> > ui/gem-icons.js
#   both from https://repoe-fork.github.io/ for the current patch
# Keys are lowercase names without " Support", matching how the app compares gems.
# Transfigured gems have no picture of their own in the data, so they get their base gem's.
# Values are art paths; the page loads https://web.poecdn.com/image/<path>.png.
import sys, json


def key(name):
    k = name.strip().lower()
    return k[: -len(" support")] if k.endswith(" support") else k


bases = json.load(open(sys.argv[1]))
gems = json.load(open(sys.argv[2]))
icons, by_id = {}, {}
for item_id, b in bases.items():
    if "Gem" not in b.get("item_class", "") or b.get("release_state") != "released":
        continue
    art = b.get("visual_identity", {}).get("dds_file", "")
    if not art.endswith(".dds") or not b.get("name"):
        continue
    art = art[: -len(".dds")]
    by_id[item_id] = art
    # the first released base with a name wins (royale and other copies come later)
    icons.setdefault(key(b["name"]), art)
for g in gems.values():
    name, base = g.get("display_name") or "", (g.get("base_item") or {}).get("id")
    if name and base in by_id:
        icons.setdefault(key(name), by_id[base])

print("// Generated by scripts/extract_gem_icons.py from RePoE; do not edit.")
print("// Gem name (lowercase, no \" Support\") → art path on https://web.poecdn.com/image/<path>.png")
print("window.GemIcons = " + json.dumps(dict(sorted(icons.items())), separators=(",", ":")))
